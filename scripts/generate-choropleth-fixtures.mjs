/**
 * Bakes the two pack-derived choropleth fixture datasets into
 * src/core/charts/choropleth/fixtures.generated.ts.
 *
 * Why: `fixtures` is a required field of ChartDefinition, so evaluating
 * WORLD_PACK.regions.map(...) and US_STATES_PACK.regions.map(...) at MODULE
 * LOAD in fixtures.ts would keep ~99 KB gzip of baked geometry alive in every
 * bundle that touches the choropleth definition, although layout does not
 * import packs statically. The derivation is a pure function of
 * the packs, so it is computed once here instead.
 *
 * The derivation below is the ONE authority for these values. Exactness is
 * gated twice: `--check` fails when this file and the generated module
 * disagree, and the product tests re-derives the values
 * from the live packs and compares them element by element.
 *
 * Usage: node scripts/generate-choropleth-fixtures.mjs [--check]
 */

import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = dirname(scriptDirectory);
const generatedPath = join(
  repositoryRoot,
  'src/core/charts/choropleth/fixtures.generated.ts',
);
const argv = process.argv.slice(2);
const checkOnly = argv.includes('--check');
const unexpectedArguments = argv.filter((argument) => argument !== '--check');
if (unexpectedArguments.length > 0) {
  throw new Error(`unknown argument: ${unexpectedArguments.join(', ')}`);
}

const require = createRequire(join(repositoryRoot, 'package.json'));
const esbuild = require('esbuild');

// ---------------------------------------------------------------------------
// The derivation.
// ---------------------------------------------------------------------------

const worldInflationTopRegions = [
  'AR',
  'CD',
  'DZ',
  'ET',
  'IN',
  'IR',
  'KZ',
  'LY',
  'MX',
  'SA',
  'SD',
  'TZ',
];

function illustrativeValue(id, minimum, tenths) {
  const score = [...id].reduce(
    (total, character, index) => total + character.charCodeAt(0) * (index + 3) * 17,
    0,
  );
  return Math.round((minimum + (score % tenths) / 10) * 10) / 10;
}

function worldInflationValue(id) {
  const topIndex = worldInflationTopRegions.findIndex((entry) => entry === id);
  return topIndex === -1
    ? illustrativeValue(id, 0.6, 78)
    : Math.round((10 - topIndex / 10) * 10) / 10;
}

// ---------------------------------------------------------------------------

async function readPackRegionIds() {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), 'boardplot-choropleth-fixtures-'));
  try {
    const entryPath = join(temporaryDirectory, 'packs-entry.ts');
    const outPath = join(temporaryDirectory, 'packs.mjs');
    const packsDirectory = join(repositoryRoot, 'src/core/geo/packs');
    await writeFile(
      entryPath,
      [
        `import { US_STATES_PACK } from ${JSON.stringify(join(packsDirectory, 'us-states.generated'))};`,
        `import { WORLD_PACK } from ${JSON.stringify(join(packsDirectory, 'world.generated'))};`,
        'export const worldIds = WORLD_PACK.regions.map((region) => region.id);',
        'export const usStateIds = US_STATES_PACK.regions.map((region) => region.id);',
        '',
      ].join('\n'),
    );
    await esbuild.build({
      entryPoints: [entryPath],
      outfile: outPath,
      bundle: true,
      format: 'esm',
      platform: 'node',
      logLevel: 'silent',
      absWorkingDir: repositoryRoot,
    });
    return await import(pathToFileURL(outPath).href);
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

function renderRows(rows) {
  return rows.map((row) => `  { id: '${row.id}', value: ${row.value} },`).join('\n');
}

const { worldIds, usStateIds } = await readPackRegionIds();

// Antarctica has no inflation rate; it stays an empty region on the map.
const worldInflation = worldIds.filter((id) => id !== 'AQ').map((id) => ({ id, value: worldInflationValue(id) }));
const usMarginByState = usStateIds.map((id) => ({
  id,
  value: illustrativeValue(id, 8.5, 136),
}));

for (const [name, rows] of [
  ['WORLD_INFLATION', worldInflation],
  ['US_MARGIN_BY_STATE', usMarginByState],
]) {
  if (rows.length === 0) throw new Error(`${name} came out empty — pack region ids missing`);
  for (const row of rows) {
    if (!/^[A-Za-z0-9_-]+$/.test(row.id)) throw new Error(`unquotable region id: ${row.id}`);
    if (!Number.isFinite(row.value)) throw new Error(`non-finite value for ${row.id}`);
  }
}

const generatedModule = [
  '// Generated by scripts/generate-choropleth-fixtures.mjs. Do not edit by hand.',
  '// Pre-baked so choropleth fixtures never evaluate WORLD_PACK/US_STATES_PACK at',
  '// module load — `fixtures` is an eager ChartDefinition field, so that import',
  '// pinned ~99 KB gzip of baked geometry into every choropleth bundle.',
  '',
  "import type { ChoroplethDatum } from './types';",
  '',
  `export const WORLD_INFLATION: ChoroplethDatum[] = [`,
  renderRows(worldInflation),
  '];',
  '',
  `export const US_MARGIN_BY_STATE: ChoroplethDatum[] = [`,
  renderRows(usMarginByState),
  '];',
  '',
].join('\n');

if (checkOnly) {
  const current = await readFile(generatedPath, 'utf8').catch(() => '');
  if (current !== generatedModule) {
    throw new Error(
      'src/core/charts/choropleth/fixtures.generated.ts is stale; run npm run generate:choropleth-fixtures',
    );
  }
  console.log(
    `choropleth fixtures up to date: ${worldInflation.length} world rows, ${usMarginByState.length} us-states rows`,
  );
} else {
  await writeFile(generatedPath, generatedModule);
  console.log(
    `wrote ${generatedPath}: ${worldInflation.length} world rows, ${usMarginByState.length} us-states rows`,
  );
}
