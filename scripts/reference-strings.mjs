/**
 * The built-in words a chart prints, read from the English tables in
 * src/core/strings.ts and src/core/strings/*.ts: the key list that validation
 * checks `options.strings` against, and the reference page that lists every key.
 */
import { readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const STRINGS_DIRECTORY = resolve(ROOT, 'src/core/strings');
/** ui.ts holds the host wording of the React placeholders (refusal, loading), which a chart option never takes. */
const HOST_ONLY_TABLES = new Set(['ui.ts']);
const HEADER = 'Generated by scripts/generate-reference.mjs from the English tables in src/core/strings. Do not edit by hand.';

/** [table name, English words] for the shared table first, then each chart table by file name. */
export async function loadTables() {
  const files = readdirSync(STRINGS_DIRECTORY).filter((file) => file.endsWith('.ts') && !HOST_ONLY_TABLES.has(file) && !file.endsWith('.generated.ts')).sort();
  const modules = [['shared', resolve(ROOT, 'src/core/strings.ts')], ...files.map((file) => [file.replace(/\.ts$/, ''), resolve(STRINGS_DIRECTORY, file)])];
  return Promise.all(modules.map(async ([name, path]) => [name, (await import(pathToFileURL(path).href)).EN]));
}

/** key -> { text, table }: the first table that holds a key names it. */
function entries(tables) {
  const found = new Map();
  for (const [table, words] of tables) {
    for (const [key, text] of Object.entries(words)) if (!found.has(key)) found.set(key, { text, table });
  }
  return found;
}

/** The key names only: validation reads them, and the browser never loads this file. */
export function stringKeysModule(tables) {
  const keys = [...entries(tables).keys()].sort();
  return [`// ${HEADER}`, '',
    '/** Every key of the built-in word tables. A chart takes any of them in `options.strings`. */',
    `export const BUILT_IN_WORD_KEYS = ${JSON.stringify(keys)} as const;`, ''].join('\n');
}

const cell = (text) => `\`${String(text).replaceAll('`', "'").replaceAll('|', '\\|').replaceAll('\n', ' ')}\``;

/** One page with every key and its English default. options.md names the documented keys only. */
export function stringsPage(tables) {
  const found = entries(tables);
  const rows = [...found].sort(([a], [b]) => (a < b ? -1 : 1)).map(([key, { text, table }]) => `| ${cell(key)} | ${cell(text)} | ${table} |`);
  return [`<!-- ${HEADER} -->`, '',
    '# Built-in words', '',
    `Every word a chart prints itself can be replaced in \`options.strings\`, or for all charts in \`BoardplotTheme\`. This page lists all ${found.size} keys with their English default. A retired key still draws with an \`option-deprecated\` warning. An unknown key is refused with the nearest key as the hint. Authored text, such as titles and series names, is never changed.`, '',
    'A word with a field in braces, such as `{count}`, keeps the field in the replacement. A word written for a plural, such as `{v1|slice|slices}`, keeps that form.', '',
    '| Key | English default | Table |', '|---|---|---|', ...rows, ''].join('\n');
}
