function inline(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(inline).join(', ')}]`;
  const entries = Object.entries(value).map(([key, item]) => `${JSON.stringify(key)}: ${inline(item)}`);
  return entries.length ? `{ ${entries.join(', ')} }` : '{}';
}

/** JSON with every array or object that fits in 100 columns on one line. */
export function compactJson(value, indent = '') {
  const flat = inline(value);
  if (flat.length + indent.length <= 100 || value === null || typeof value !== 'object') return flat;
  const inner = `${indent}  `;
  const entries = Array.isArray(value)
    ? value.map((item) => `${inner}${compactJson(item, inner)}`)
    : Object.entries(value).map(([key, item]) => `${inner}${JSON.stringify(key)}: ${compactJson(item, inner)}`);
  return Array.isArray(value) ? `[\n${entries.join(',\n')}\n${indent}]` : `{\n${entries.join(',\n')}\n${indent}}`;
}

/**
 * The value cell is described once in options.md: a field whose children are
 * a cell's folds into one row and its children are left out.
 */
function foldCells(rows) {
  const folded = [];
  const out = [];
  for (const field of rows) {
    if (folded.some((prefix) => field.path.startsWith(`${prefix}.`) || field.path.startsWith(`${prefix}[]`))) continue;
    const cell = cellType(rows, field.path);
    if (cell) folded.push(field.path);
    out.push(cell ? { ...field, type: cell } : field);
  }
  return out;
}

function allFixtures(type) {
  const found = [];
  let cursor;
  do {
    const page = body(fixtures({ type, kind: 'all', ...(cursor ? { cursor } : {}) }));
    found.push(...page.fixtures);
    cursor = page.nextCursor;
  } while (cursor);
  return found;
}

/** Anchors follow GitHub's heading slugs; the anchor check uses the same rule. */
export function slug(heading) {
  return heading.trim().toLowerCase().replace(/[^\p{L}\p{N}\- ]/gu, '').replace(/ /g, '-');
}

/** A page over 100 lines gets a contents line under its title. */
function withContents(lines) {
  if (lines.join('\n').split('\n').length <= 100) return lines;
  const headings = lines.filter((line) => line.startsWith('## ')).map((line) => line.slice(3));
  const contents = `Contents: ${headings.map((heading) => `[${heading}](#${slug(heading)})`).join(', ')}.`;
  return [lines[0], '', contents, ...lines.slice(1)];
}

