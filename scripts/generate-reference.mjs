/** "36 chart types, 81 variants and 654 example specs": variants are the chart IDs of `boardplot list`. */
function countsText(list) {
  const variants = list.types.reduce((sum, entry) => sum + (entry.ids?.length ?? 1), 0);
  const examples = list.types.reduce((sum, entry) => sum + allFixtures(entry.type).filter((fixture) => fixture.kind === 'example').length, 0);
  return `${list.types.length} chart types, ${variants} variants and ${examples} example specs`;
}

/** The summary without the CLI rows grammar that some types append for agents ("Bridge; rows label,value[,type]"). */
export const plainSummary = (entry) => entry.summary.replace(/; rows .*$/, '');

function catalogBlock(list, counts) {
  return [BEGIN_MARKER, GENERATED, '## The catalog', '', `${counts[0].toUpperCase()}${counts.slice(1)}. [fixtures.md](docs/reference/fixtures.md) lists every example spec.`, '',
    table(['Type', 'Aliases', 'Summary'], list.types.map((entry) => [`[\`${entry.type}\`](docs/reference/${entry.type}.md)`, (entry.aliases ?? []).map((alias) => `\`${alias}\``).join(', '), plainSummary(entry)])),
    END_MARKER].join('\n');
}

/** `file` with the text between its two markers replaced by `block`, which carries the markers. */
function spliced(file, beginMarker, endMarker, block, source = readFileSync(resolve(ROOT, file), 'utf8')) {
  const begin = source.indexOf(beginMarker);
  const end = source.indexOf(endMarker);
  if (begin === -1 || end < begin) throw new Error(`${file} lacks the markers ${beginMarker}`);
  return `${source.slice(0, begin)}${block}${source.slice(end + endMarker.length)}`;
}

/** The manual's type size and floor tables, from TARGET_TYPE_TABLES. */
function typeSizesBlock() {
  const roles = ['title', 'subtitle', 'label', 'axis', 'secondary', 'footnote', 'micro'];
  const head = ['Title', 'Subtitle', 'Label', 'Axis', 'Secondary', 'Footnote/source', 'Micro'];
  const targets = Object.entries(TARGET_TYPE_TABLES);
  const sizes = targets.flatMap(([target, t]) => ['S', 'M', 'L'].map((step) => [`\`${target}\``, t.unit, step, ...roles.map((role) => t[step][role])]));
  const floors = targets.map(([target, t]) => [`\`${target}\``, t.unit, ...roles.map((role) => t.floors[role])]);
  return [TYPE_BEGIN, '<!-- Generated by scripts/generate-reference.mjs from TARGET_TYPE_TABLES in src/core/target.ts. -->',
    table(['Target', 'Unit', 'Class', ...head], sizes), '',
    'The engine never fits text below the floor of its target. The floors apply to the size the reader sees, after display scaling.', '',
    table(['Target', 'Unit', ...head], floors), TYPE_END].join('\n');
}

/** Where the plugin skill keeps its copy of the manual. */
const SKILL_MANUAL = 'release/plugin/boardplot-marketplace/plugins/boardplot/skills/boardplot-chart/references/manual.md';

/**
 * The manual as the plugin skill reads it. Links point from docs/; they are
 * re-rooted to the runtime copy of docs/ that the offline ZIP bundles under
 * the plugin root. A marketplace install has no runtime folder; the skill
 * names the MCP tools for those pages instead.
 */
function skillManual(manual) {
  const from = posix.dirname(SKILL_MANUAL.replace(/^.*\/plugins\/boardplot\//, ''));
  const body = manual.replace(/\]\(([^)\s#][^)\s]*)\)/g, (link, target) => {
    if (/^[a-z]+:/i.test(target)) return link;
    return `](${posix.relative(from, posix.normalize(posix.join('runtime/docs', target)))})`;
  });
  return `<!-- Generated by scripts/generate-reference.mjs from docs/manual.md. -->\n\n${body}`;
}

/** Every generated file, keyed by its path from the repository root. */
export function generatedFiles() {
  const listed = catalogue();
  const types = listed.types.map((entry) => entry.type);
  const pages = new Map(types.map((type) => [`docs/reference/${type}.md`, typePage(type, listed.anchor)]));
  pages.set('docs/reference/options.md', optionsPage(listed));
  pages.set('docs/reference/theme.md', themePage());
  pages.set('docs/reference/react.md', reactPage());
  pages.set('docs/reference/fixtures.md', fixturesPage(types));
  const manual = spliced('docs/manual.md', TYPE_BEGIN, TYPE_END, typeSizesBlock());
  // Update the root README and the release template when present.
  const readmes = ['README.md', 'release/public/README.md'].filter((file) => existsSync(resolve(ROOT, file)));
  const counts = countsText(listed);
  const readme = (file) => {
    const text = spliced(file, BEGIN_MARKER, END_MARKER, catalogBlock(listed, counts));
    return text.includes(COUNTS_BEGIN) ? spliced(file, COUNTS_BEGIN, COUNTS_END, `${COUNTS_BEGIN}${counts}${COUNTS_END}`, text) : text;
  };
  return new Map([...pages, ['llms.txt', llmsIndex(listed)],
    ...readmes.map((file) => [file, readme(file)]),
    ['docs/manual.md', manual], [SKILL_MANUAL, skillManual(manual)],
    ...galleryFiles({ list: listed, counts, summary: plainSummary, specJson: compactJson, slug })]);
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  const files = generatedFiles();
  for (const [file, content] of files) {
    const path = resolve(ROOT, file);
    if (existsSync(path) && readFileSync(path, 'utf8') === content) continue;
    if (check) {
      console.error(`${relative(ROOT, path)} is stale; run npm run docs:build`);
      stale += 1;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content, 'utf8');
    }
  }
  // docs/gallery holds generated files only: one the generator no longer writes is a dropped pick.
  for (const name of readdirSync(resolve(ROOT, 'docs/gallery'))) {
    const file = `docs/gallery/${name}`;
    if (files.has(file)) continue;
    if (check) {
      console.error(`${file} is no longer generated; run npm run docs:build`);
      stale += 1;
    } else {
      rmSync(resolve(ROOT, file));
    }
  }
  return stale === 0 ? 0 : 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
