/** Deterministic integer sample: a fixed lattice, never Math.random. */
function ramp(count: number, from: number, to: number): number[] {
  if (count === 1) return [from];
  const stepSize = (to - from) / (count - 1);
  return Array.from({ length: count }, (_, index) => Math.round((from + stepSize * index) * 10) / 10);
}

/**
 * A symmetric, centre-dense sample spanning [lo, hi]: `u * |u|` keeps the
 * middle half tight and spreads the tails, which is both realistic for pay
 * bands and legible — coincident tail dots would draw as one blob.
 */
function bell(count: number, lo: number, hi: number): number[] {
  const mid = (lo + hi) / 2;
  const half = (hi - lo) / 2;
  return Array.from({ length: count }, (_, index) => {
    const u = 2 * (index / (count - 1)) - 1;
    return Math.round((mid + half * u * Math.abs(u)) * 10) / 10;
  });
}

/**
 * A right-skewed sample: a dense body plus a thinning tail. Built from a fixed
 * closed form so the shape is reproducible and readable in the source.
 */
function skewed(count: number, base: number, spread: number): number[] {
  return Array.from({ length: count }, (_, index) => {
    const t = index / (count - 1);
    return Math.round((base + spread * t * t * t) * 10) / 10;
  });
}

