"use client";

// boardplot/react: every chart component, BoardplotTheme, ScaleGroup,
// useChartLayout and SceneRenderer from one import.
//
// What it links: the loop below registers every chart core, and the
// components come from every per-type entry, pareto's and likert's link
// calls included. `dist/react/index.js` is on the package's `sideEffects`
// list, so a bundler keeps that body. A page that imports this barrel
// therefore links the whole catalogue, the annotation engine and the theme
// checks, whichever names it uses. Map geometry is not linked: a choropleth
// consumer registers the pack they draw (`import 'boardplot/geo/world'`).
//
// The components are this barrel's own bindings (src/react/barrelCharts.ts,
// generated by scripts/generate-chart-entries.mjs): each type's component
// built again with both fetched modules linked. A server pass and the pass
// that hydrates it may then use those modules, because every page that
// imports the barrel holds them. The per-type entries keep their own
// bindings, which count only what their entry links. A host that wants a
// small bundle imports `boardplot/react/<type>` or `boardplot/react/spec`
// instead, with the theme provider and the other shared pieces from
// `boardplot/react/theme` (src/react/theme.ts), which registers no core.
//
// The package smoke test (`scripts/package-smoke.mjs`) bundles the real
// tarball with a real bundler.

